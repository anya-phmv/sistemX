  setServiceCardSlide(serviceId, slideIndex, e) {
    if (e) e.stopPropagation();
    const service = APP_DATA.services.find(s => s.id === serviceId);
    if (!service) return;
    service.activeSlide = slideIndex;
    const track = document.getElementById(`track-${serviceId}`);
    if (track) {
      track.style.transform = `translateX(-${slideIndex * 25}%)`;
    }
    const carousel = document.getElementById(`carousel-${serviceId}`);
    if (carousel) {
      const dots = carousel.querySelectorAll('.service-carousel-dot');
      dots.forEach((dot, idx) => {
        const dist = Math.abs(idx - slideIndex);
        dot.className = 'service-carousel-dot ' + (dist === 0 ? 'active' : (dist === 1 ? 'near' : 'far'));
      });
    }
  },

