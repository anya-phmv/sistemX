  // Toast System
  showToast(message, type = "info") {
    const toastRoot = document.getElementById("toast-root");
    if (!toastRoot) return;

    const toast = document.createElement("div");
    const bgColors = {
      success: "bg-primary-600 text-white",
      info: "bg-gray-900 text-white",
      warning: "bg-amber-500 text-white"
    };

    toast.className = `px-4 py-3 rounded-xl shadow-xl flex items-center gap-3 text-sm font-medium transform transition-all duration-300 translate-y-3 opacity-0 ${bgColors[type] || bgColors.info}`;
    toast.innerHTML = `
      <span>${type === 'success' ? '✓' : 'ℹ'}</span>
      <span>${message}</span>
    `;

    toastRoot.appendChild(toast);
    setTimeout(() => {
      toast.classList.remove("translate-y-3", "opacity-0");
    }, 10);

    setTimeout(() => {
      toast.classList.add("opacity-0", "translate-y-2");
      setTimeout(() => toast.remove(), 300);
    }, 3200);
  },

